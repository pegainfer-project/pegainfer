fn ensure_git_submodules_initialized(repo_root: &Path) {
    if !repo_root.join(".git").exists() || !repo_root.join(".gitmodules").is_file() {
        return;
    }

    println!(
        "cargo:rerun-if-changed={}",
        repo_root.join(".gitmodules").display()
    );

    let output = Command::new("git")
        .args(["submodule", "status", "--recursive"])
        .current_dir(repo_root)
        .output()
        .unwrap_or_else(|err| {
            panic!(
                "Failed to inspect git submodules from {}: {err}. \
                 Install git or run `git submodule update --init --recursive` manually.",
                repo_root.display()
            )
        });
    assert!(
        output.status.success(),
        "Failed to inspect git submodules from {}. stdout: {} stderr: {}",
        repo_root.display(),
        String::from_utf8_lossy(&output.stdout).trim(),
        String::from_utf8_lossy(&output.stderr).trim()
    );

    if !String::from_utf8_lossy(&output.stdout)
        .lines()
        .any(|line| line.starts_with('-'))
    {
        return;
    }

    println!("cargo:warning=Initializing missing git submodules for first build");
    let output = Command::new("git")
        .args(["submodule", "update", "--init", "--recursive"])
        .current_dir(repo_root)
        .output()
        .unwrap_or_else(|err| {
            panic!(
                "Failed to initialize git submodules from {}: {err}. \
                 Run `git submodule update --init --recursive` manually.",
                repo_root.display()
            )
        });
    assert!(
        output.status.success(),
        "Failed to initialize git submodules from {}. stdout: {} stderr: {}",
        repo_root.display(),
        String::from_utf8_lossy(&output.stdout).trim(),
        String::from_utf8_lossy(&output.stderr).trim()
    );
}

fn build_timing_enabled() -> bool {
    std::env::var("PEGAINFER_BUILD_TIMING").is_ok_and(|value| {
        let value = value.trim().to_ascii_lowercase();
        !(value.is_empty() || value == "0" || value == "false" || value == "off")
    })
}

fn time_phase<T>(label: impl AsRef<str>, f: impl FnOnce() -> T) -> T {
    if !build_timing_enabled() {
        return f();
    }

    let started = Instant::now();
    let result = f();
    println!(
        "cargo:warning=build-timing {} {:.3}s",
        label.as_ref(),
        started.elapsed().as_secs_f64()
    );
    result
}

fn parse_job_count_env(name: &str) -> Option<usize> {
    let value = std::env::var(name).ok()?;
    match value.trim().parse::<usize>() {
        Ok(jobs) if jobs > 0 => Some(jobs),
        _ => {
            println!("cargo:warning=Ignoring invalid {name}={value}; expected a positive integer.");
            None
        }
    }
}

fn nvcc_job_count() -> usize {
    if let Some(jobs) = parse_job_count_env("PEGAINFER_NVCC_JOBS") {
        return jobs;
    }

    parse_job_count_env("NUM_JOBS")
        .or_else(|| thread::available_parallelism().ok().map(usize::from))
        .unwrap_or(1)
        .max(1)
}

fn nvcc_task_priority(cu_file: &Path) -> usize {
    match cu_file.file_stem().and_then(|stem| stem.to_str()) {
        Some("paged_attention") => 0,
        Some("paged_attention_hd512" | "flashinfer_sampling") => 1,
        Some("flashinfer_top1") => 2,
        Some("flashinfer_norm") => 3,
        _ => 10,
    }
}

fn parse_sm_token(raw: &str) -> Option<String> {
    let token = raw.trim().trim_matches('"');
    if token.is_empty() {
        return None;
    }

    let token = token
        .strip_prefix("sm_")
        .or_else(|| token.strip_prefix("compute_"))
        .unwrap_or(token);

    if let Some((major, minor)) = token.split_once('.') {
        let digit_count = minor.chars().take_while(char::is_ascii_digit).count();
        let (minor_digits, suffix) = minor.split_at(digit_count);
        if major.chars().all(|c| c.is_ascii_digit())
            && !minor_digits.is_empty()
            && suffix.chars().all(|c| c.is_ascii_alphabetic())
        {
            return Some(format!("{major}{minor_digits}{suffix}"));
        }
        return None;
    }

    let digit_count = token.chars().take_while(char::is_ascii_digit).count();
    let (digits, suffix) = token.split_at(digit_count);
    if !digits.is_empty() && suffix.chars().all(|c| c.is_ascii_alphabetic()) {
        if digits.len() == 1 {
            return Some(format!("{digits}0{suffix}"));
        }
        return Some(format!("{digits}{suffix}"));
    }

    None
}

fn nvcc_supported_arches(nvcc: &str) -> Option<BTreeSet<String>> {
    let output = Command::new(nvcc).arg("--list-gpu-arch").output().ok()?;
    if !output.status.success() {
        return None;
    }

    Some(
        String::from_utf8_lossy(&output.stdout)
            .lines()
            .map(str::trim)
            .filter(|line| line.starts_with("compute_"))
            .map(str::to_string)
            .collect(),
    )
}

fn normalize_nvcc_sm(sm: &str, supported_arches: Option<&BTreeSet<String>>) -> String {
    let preferred = match sm {
        "120" | "120f" => Some("120f"),
        "121" | "121a" => Some("121a"),
        _ => None,
    };
    if let Some(preferred) = preferred {
        if supported_arches.is_some_and(|arches| arches.contains(&format!("compute_{preferred}"))) {
            return preferred.to_string();
        }
        let raw = sm_numeric_prefix(sm).map_or_else(|| sm.to_string(), |sm| sm.to_string());
        println!(
            "cargo:warning=nvcc does not list compute_{preferred}; compiling CUDA kernels for raw sm_{raw}"
        );
        return raw;
    }
    sm.to_string()
}

fn normalize_nvcc_sms(sm_targets: &[String], nvcc: &str) -> Vec<String> {
    let supported_arches = nvcc_supported_arches(nvcc);
    sm_targets
        .iter()
        .map(|sm| normalize_nvcc_sm(sm, supported_arches.as_ref()))
        .collect()
}

fn sm_targets_from_nvidia_smi() -> Option<Vec<String>> {
    let output = Command::new("nvidia-smi")
        .args(["--query-gpu=compute_cap", "--format=csv,noheader"])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }

    let stdout = String::from_utf8_lossy(&output.stdout);
    let mut sms = BTreeSet::new();
    for line in stdout.lines() {
        let cap = line.split(',').next().unwrap_or(line).trim();
        if let Some(sm) = parse_sm_token(cap) {
            sms.insert(sm);
        }
    }

    if sms.is_empty() {
        None
    } else {
        Some(sms.into_iter().collect())
    }
}

fn detect_sm_targets() -> Vec<String> {
    if let Ok(env) = std::env::var("PEGAINFER_CUDA_SM").or_else(|_| std::env::var("CUDA_SM")) {
        let mut sms = Vec::new();
        for token in env.split(',') {
            if let Some(sm) = parse_sm_token(token) {
                sms.push(sm);
            } else {
                print!(
                    "cargo:warning=Invalid SM token '{}' in CUDA_SM environment variable, skipping.",
                    token
                );
            }
        }
        if !sms.is_empty() {
            return sms;
        }
        print!(
            "cargo:warning=No valid SM tokens found in CUDA_SM environment variable '{}', falling back to auto-detection.",
            env
        );
    }

    if let Some(sms) = sm_targets_from_nvidia_smi() {
        return sms;
    }

    print!(
        "cargo:warning=Failed to detect GPU SMs via nvidia-smi. Set PEGAINFER_CUDA_SM/CUDA_SM environment variable to override."
    );
    panic!("GPU detection failed");
}

fn nvcc_arch_args(normalized_sms: &[String]) -> Vec<String> {
    let mut args = Vec::new();
    for sm in normalized_sms {
        args.push("-gencode".to_string());
        args.push(format!("arch=compute_{sm},code=sm_{sm}"));
    }

    if let Some(max_sm) = normalized_sms
        .iter()
        .max_by_key(|sm| sm_numeric_prefix(sm).unwrap_or(0))
    {
        args.push("-gencode".to_string());
        args.push(format!("arch=compute_{max_sm},code=compute_{max_sm}"));
    }

    args
}

fn nvcc_accepts_gencode(nvcc: &str, compute: &str, sm: &str) -> bool {
    let stem = format!(
        "pegainfer_nvcc_probe_{}_compute_{compute}_sm_{sm}",
        std::process::id()
    );
    let cu_path = std::env::temp_dir().join(format!("{stem}.cu"));
    let obj_path = std::env::temp_dir().join(format!("{stem}.o"));
    if let Err(err) = fs::write(
        &cu_path,
        "extern \"C\" __global__ void pegainfer_nvcc_probe() {}\n",
    ) {
        println!(
            "cargo:warning=Failed to write nvcc probe {}: {err}",
            cu_path.display()
        );
        return false;
    }

    let output = Command::new(nvcc)
        .args(["-c"])
        .arg(&cu_path)
        .arg("-o")
        .arg(&obj_path)
        .arg("-gencode")
        .arg(format!("arch=compute_{compute},code=sm_{sm}"))
        .output();
    let _ = fs::remove_file(&cu_path);
    let _ = fs::remove_file(&obj_path);

    match output {
        Ok(output) if output.status.success() => true,
        Ok(output) => {
            println!(
                "cargo:warning=nvcc rejected compute_{compute}/sm_{sm} probe: {}",
                String::from_utf8_lossy(&output.stderr).trim()
            );
            false
        }
        Err(err) => {
            println!("cargo:warning=Failed to run nvcc arch probe: {err}");
            false
        }
    }
}

fn glm52_fp8_gemm_arch_args(normalized_sms: &[String], nvcc: &str) -> Option<Vec<String>> {
    let mut args = Vec::new();
    for sm in normalized_sms {
        let numeric = sm_numeric_prefix(sm)?;
        if !(100..120).contains(&numeric) {
            continue;
        }
        let accelerated = format!("{numeric}a");
        if !nvcc_accepts_gencode(nvcc, &accelerated, &accelerated) {
            continue;
        }
        args.push("-gencode".to_string());
        args.push(format!("arch=compute_{accelerated},code=sm_{accelerated}"));
    }
    (!args.is_empty()).then_some(args)
}

fn glm52_flashmla_sparse_arch_args(normalized_sms: &[String], nvcc: &str) -> Vec<String> {
    let sm90a_supported = normalized_sms.iter().any(|sm| sm == "90" || sm == "90a")
        && nvcc_accepts_gencode(nvcc, "90a", "90a");
    let sm100f_supported = normalized_sms
        .iter()
        .any(|sm| sm_numeric_prefix(sm).is_some_and(|n| (100..120).contains(&n)))
        && nvcc_accepts_gencode(nvcc, "100f", "100f");

    let mut targets = Vec::new();
    for sm in normalized_sms {
        let target = match sm_numeric_prefix(sm) {
            Some(90) => {
                if sm90a_supported {
                    Some(("90a", "90a", "sm_90a"))
                } else {
                    println!(
                        "cargo:warning=nvcc cannot compile compute_90a/sm_90a; GLM5.2 FlashMLA sparse decode will use sm_{sm}"
                    );
                    Some((sm.as_str(), sm.as_str(), "native"))
                }
            }
            Some(100..=119) => {
                if sm100f_supported {
                    Some(("100f", "100f", "sm_100f"))
                } else {
                    println!(
                        "cargo:warning=nvcc cannot compile compute_100f/sm_100f; GLM5.2 FlashMLA sparse decode will use sm_{sm}"
                    );
                    Some((sm.as_str(), sm.as_str(), "native"))
                }
            }
            _ => Some((sm.as_str(), sm.as_str(), "native")),
        };
        if let Some(target) = target {
            if !targets.iter().any(|existing| existing == &target) {
                targets.push(target);
            }
        }
    }

    let labels = targets
        .iter()
        .map(|(_, sm, label)| {
            if *label == "native" {
                format!("sm_{sm}")
            } else {
                label.to_string()
            }
        })
        .collect::<Vec<_>>();
    if labels
        != normalized_sms
            .iter()
            .map(|sm| format!("sm_{sm}"))
            .collect::<Vec<_>>()
    {
        println!(
            "cargo:warning=Compiling GLM5.2 FlashMLA sparse decode for nvcc targets: {}",
            labels.join(",")
        );
    }

    let mut args = Vec::new();
    for (compute, sm, _) in targets {
        args.push("-gencode".to_string());
        args.push(format!("arch=compute_{compute},code=sm_{sm}"));
    }
    args
}

/// Arch args for the AOT-instantiated DeepGEMM MQA kernels. GLM5.2 is
/// Blackwell-only: assembled as sm_100f (tcgen05). Hopper SM90A path removed.
fn glm52_deepgemm_mqa_arch_args(
    normalized_sms: &[String],
    nvcc: &str,
) -> Option<(Vec<String>, String)> {
    let has_sm100 = normalized_sms
        .iter()
        .any(|sm| sm_numeric_prefix(sm).is_some_and(|n| (100..120).contains(&n)));
    if has_sm100 && nvcc_accepts_gencode(nvcc, "100f", "100f") {
        return Some((
            vec![
                "-gencode".to_string(),
                "arch=compute_100f,code=sm_100f".to_string(),
            ],
            "-DGLM52_DEEPGEMM_MQA_SM100F".to_string(),
        ));
    }

    None
}

/// Arch args for TUs whose device code is raw Blackwell tcgen05: sm_100f
/// ONLY (family arch — runs on the whole sm_10x line, incl. GB300's sm_103).
/// Returns `None` when no sm_100 target is present (or nvcc lacks 100f); the
/// TU then compiles its NOT_SUPPORTED stub for the requested targets instead.
fn glm52_sm100f_only_arch_args(normalized_sms: &[String], nvcc: &str) -> Option<Vec<String>> {
    let has_sm100 = normalized_sms
        .iter()
        .any(|sm| sm_numeric_prefix(sm).is_some_and(|n| (100..120).contains(&n)));
    (has_sm100 && nvcc_accepts_gencode(nvcc, "100f", "100f")).then(|| {
        vec![
            "-gencode".to_string(),
            "arch=compute_100f,code=sm_100f".to_string(),
        ]
    })
}

