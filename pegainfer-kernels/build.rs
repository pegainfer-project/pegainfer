fn main() {
    ensure_git_submodules_initialized(&workspace_root());

    let toolkit = pegainfer_build::CudaToolkit::discover();
    let nvcc = toolkit.nvcc.to_string_lossy().into_owned();
    let cuda_include = toolkit
        .header_dir("cuda.h")
        .unwrap_or_else(|| toolkit.root.join("include"));
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let sm_targets = detect_sm_targets();
    let nvcc_sm_targets = normalize_nvcc_sms(&sm_targets, &nvcc);
    let arch_args = nvcc_arch_args(&nvcc_sm_targets);
    let deepseek_v2_lite_enabled = cfg!(feature = "deepseek-v2-lite");
    let moe_enabled = cfg!(feature = "moe");
    let gemma4_enabled = cfg!(feature = "gemma4");
    let glm52_enabled = cfg!(feature = "glm52");
    let kimi_k2_enabled = cfg!(feature = "kimi-k2");
    // --- k3: DeepGEMM-only, no DeepEP/NCCL dependency ---
    let k3_enabled = cfg!(feature = "k3");
    let qwen35_enabled = cfg!(feature = "qwen35");
    if glm52_enabled {
        generate_glm52_trtllm_fmha_cubins(&crate_root(), &out_dir);
        build_glm52_cutedsl_fp8_dsl(&crate_root(), &out_dir, &cuda_include);
    }
    println!(
        "cargo:warning=Detected CUDA SM targets: {}",
        sm_targets
            .iter()
            .map(|sm| format!("sm_{sm}"))
            .collect::<Vec<_>>()
            .join(",")
    );
    println!(
        "cargo:warning=Compiling CUDA kernels for nvcc targets: {}",
        nvcc_sm_targets
            .iter()
            .map(|sm| format!("sm_{sm}"))
            .collect::<Vec<_>>()
            .join(",")
    );

    let replaced_cuda_files =
        BTreeSet::from(["activation.cu", "embedding.cu", "fused_attention.cu"]);

    let root = crate_root();
    if moe_enabled {
        require_moe_submodules(&root);
    }
    if glm52_enabled {
        require_glm52_submodules(&root);
    }
    // --- k3 ---
    if k3_enabled {
        require_k3_submodules(&root);
    }
    // --- end k3 ---
    let csrc_dir = root.join("csrc");
    let mut csrc_files = Vec::new();
    collect_files_recursively(&csrc_dir, &mut csrc_files);
    let mut cu_files: Vec<_> = csrc_files
        .iter()
        .filter_map(|path| {
            let file_name = path.file_name()?.to_str()?;
            if !deepseek_v2_lite_enabled && is_deepseek_v2_lite_source(&csrc_dir, path) {
                return None;
            }
            if !moe_enabled && is_deepep_source(&csrc_dir, path) {
                return None;
            }
            // The GLM5.2 shim instantiations (EP4..EP64) ride the deepep
            // flags but only exist for the glm52 feature.
            if !glm52_enabled && file_name.starts_with("deepep_shim_glm52") {
                return None;
            }
            if !gemma4_enabled && is_gemma4_source(&csrc_dir, path) {
                return None;
            }
            if !gemma4_enabled && !kimi_k2_enabled && is_marlin_source(&csrc_dir, path) {
                return None;
            }
            if !glm52_enabled && is_glm52_source(&csrc_dir, path) {
                return None;
            }
            if !kimi_k2_enabled && is_kimi_k2_source(&csrc_dir, path) {
                return None;
            }
            // --- k3 ---
            if !k3_enabled && is_k3_source(&csrc_dir, path) {
                return None;
            }
            // --- end k3 ---
            if path.extension().and_then(|e| e.to_str()) == Some("cu")
                && !replaced_cuda_files.contains(file_name)
            {
                Some(path.clone())
            } else {
                None
            }
        })
        .collect();
    cu_files.sort();
    for path in &csrc_files {
        let Some(extension) = path.extension().and_then(|extension| extension.to_str()) else {
            continue;
        };
        if matches!(extension, "cu" | "cuh") {
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }

    println!(
        "cargo:warning=Legacy CUDA translation units retired from the runtime build: {}",
        replaced_cuda_files
            .iter()
            .copied()
            .collect::<Vec<_>>()
            .join(", ")
    );

    let nvcc_jobs = nvcc_job_count();
    println!("cargo:warning=Compiling CUDA translation units with {nvcc_jobs} nvcc job(s)");
    let flashinfer = flashinfer_includes();
    println!(
        "cargo:warning=Using FlashInfer include dir: {}",
        flashinfer.include.display()
    );

    let deepep_nccl = moe_enabled.then(deepep_nccl_root);

    let mut nvcc_tasks = Vec::new();
    for cu_file in &cu_files {
        let stem = cu_file.file_stem().unwrap().to_str().unwrap();
        let obj_file = out_dir.join(cuda_object_name(&csrc_dir, cu_file));

        let mut nvcc_args = vec![
            "-c".to_string(),
            cu_file.to_string_lossy().to_string(),
            "-o".to_string(),
            obj_file.to_string_lossy().to_string(),
            "-O3".to_string(),
            "-isystem".to_string(),
            cuda_include.to_string_lossy().to_string(),
            "-I".to_string(),
            csrc_dir.to_string_lossy().to_string(),
        ];
        if stem == "glm52_fp8_gemm" {
            if let Some(args) = glm52_fp8_gemm_arch_args(&nvcc_sm_targets, &nvcc) {
                nvcc_args.extend(args);
                nvcc_args.push("-DGLM52_FP8_GEMM_SM100A".to_string());
            } else {
                nvcc_args.extend(arch_args.clone());
            }
        } else if stem == "glm52_flashmla_sparse" {
            nvcc_args.extend(glm52_flashmla_sparse_arch_args(&nvcc_sm_targets, &nvcc));
        } else if stem == "glm52_deepgemm_mqa" {
            if let Some((mqa_args, mqa_define)) =
                glm52_deepgemm_mqa_arch_args(&nvcc_sm_targets, &nvcc)
            {
                nvcc_args.extend(mqa_args);
                nvcc_args.push(mqa_define);
            } else {
                println!(
                    "cargo:warning=No sm_100f target; GLM5.2 DeepGEMM {stem} kernels compile as NOT_SUPPORTED stubs"
                );
                nvcc_args.extend(arch_args.clone());
            }
        } else if stem == "glm52_deepgemm_grouped_sm100" {
            if let Some(sm100f_args) = glm52_sm100f_only_arch_args(&nvcc_sm_targets, &nvcc) {
                nvcc_args.extend(sm100f_args);
                nvcc_args.push("-DGLM52_DEEPGEMM_GROUPED_SM100F".to_string());
            } else {
                println!(
                    "cargo:warning=No sm_100f target; GLM5.2 DeepGEMM {stem} kernels compile as NOT_SUPPORTED stubs"
                );
                nvcc_args.extend(arch_args.clone());
            }
        // --- k3 ---
        } else if stem == "k3_deepgemm_fp8_fp4_grouped_sm100" {
            if let Some(sm100f_args) = k3_sm100f_only_arch_args(&nvcc_sm_targets, &nvcc) {
                nvcc_args.extend(sm100f_args);
                nvcc_args.push("-DK3_DEEPGEMM_FP8_FP4_SM100F".to_string());
            } else {
                println!(
                    "cargo:warning=No sm_100f target; K3 DeepGEMM {stem} kernels compile as NOT_SUPPORTED stubs"
                );
                nvcc_args.extend(arch_args.clone());
            }
        } else if stem == "k3_mega_moe_sm100"
            || stem == "k3_mega_moe_sm100_wide224"
            || stem == "k3_mega_moe_sm100_wide896"
        {
            if let Some(sm100f_args) = k3_sm100f_only_arch_args(&nvcc_sm_targets, &nvcc) {
                nvcc_args.extend(sm100f_args);
                nvcc_args.push("-DK3_MEGA_MOE_SM100F".to_string());
            } else {
                println!(
                    "cargo:warning=No sm_100f target; K3 MegaMoE {stem} kernels compile as NOT_SUPPORTED stubs"
                );
                nvcc_args.extend(arch_args.clone());
            }
        } else if stem == "k3_flash_kda" {
            if let Some(kda_args) = k3_flash_kda_arch_args(&nvcc_sm_targets, &nvcc) {
                let flash_kda = root.join("third_party/flash-kda/csrc");
                nvcc_args.extend(kda_args);
                // Upstream setup.py flags (torch adds -std=c++17); fast_math
                // is part of the configuration vLLM ships, keep it.
                nvcc_args.extend(
                    [
                        "-DK3_FLASH_KDA_SM90A",
                        "--std=c++17",
                        "--expt-relaxed-constexpr",
                        "--expt-extended-lambda",
                        "--use_fast_math",
                    ]
                    .map(str::to_string),
                );
                nvcc_args.extend([
                    "-I".to_string(),
                    flash_kda.to_string_lossy().to_string(),
                    "-I".to_string(),
                    flash_kda.join("smxx").to_string_lossy().to_string(),
                    "-I".to_string(),
                    flashinfer.cutlass.to_string_lossy().to_string(),
                ]);
            } else {
                println!(
                    "cargo:warning=No accelerated SM target; K3 FlashKDA {stem} compiles as a NOT_SUPPORTED stub"
                );
                nvcc_args.extend(arch_args.clone());
            }
        } else if stem == "k3_flash_mla_prefill" {
            // FlashMLA's SM100 dense FMHA forward rides in single-TU like the
            // sparse decode shim; the gather/expand helpers in the same file
            // compile either way.
            if let Some(sm100f_args) = k3_sm100f_only_arch_args(&nvcc_sm_targets, &nvcc) {
                let flashmla = root.join("third_party/FlashMLA/csrc");
                nvcc_args.extend(sm100f_args);
                nvcc_args.extend(
                    [
                        "-DK3_FLASH_MLA_SM100F",
                        "--std=c++20",
                        "--expt-relaxed-constexpr",
                        "--expt-extended-lambda",
                    ]
                    .map(str::to_string),
                );
                nvcc_args.extend([
                    "-I".to_string(),
                    flashmla
                        .join("sm100/prefill/dense")
                        .to_string_lossy()
                        .to_string(),
                    "-I".to_string(),
                    flashmla
                        .join("cutlass/include")
                        .to_string_lossy()
                        .to_string(),
                    "-I".to_string(),
                    flashmla
                        .join("cutlass/tools/util/include")
                        .to_string_lossy()
                        .to_string(),
                    "-I".to_string(),
                    flashmla
                        .join("kerutils/include")
                        .to_string_lossy()
                        .to_string(),
                ]);
            } else {
                println!(
                    "cargo:warning=No sm_100f target; K3 FlashMLA prefill {stem} FMHA compiles as a NOT_SUPPORTED stub"
                );
                nvcc_args.extend(arch_args.clone());
            }
        // --- end k3 ---
        } else {
            nvcc_args.extend(arch_args.clone());
        }
        nvcc_args.extend(["--compiler-options".to_string(), "-fPIC".to_string()]);

        // Files that include FlashInfer headers (C++17, header-only)
        if stem == "paged_attention"
            || stem == "paged_attention_hd512"
            || stem == "flashinfer_norm"
            || stem == "flashinfer_sampling"
            || stem == "dflash2_selector"
            || stem == "flashinfer_top1"
            || stem == "glm52_topk"
            || stem == "local_kv_fp8"
        {
            for dir in &flashinfer.cccl {
                nvcc_args.extend(["-I".to_string(), dir.to_string_lossy().to_string()]);
            }
            nvcc_args.extend([
                "--std=c++17".to_string(),
                "-I".to_string(),
                flashinfer.include.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.csrc.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.cutlass.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.cutlass_util.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.spdlog.to_string_lossy().to_string(),
                "-I".to_string(),
                csrc_dir
                    .join("marlin/vllm_marlin")
                    .to_string_lossy()
                    .to_string(),
            ]);
        }

        // DeepEP elastic shim: mirrors the upstream JIT compile flags
        // (DeepEP csrc/jit/compiler.hpp) minus the cubin plumbing.
        if is_deepep_source(&csrc_dir, cu_file) {
            let nccl_root = deepep_nccl
                .as_ref()
                .expect("deepep sources are collected only with the moe feature");
            nvcc_args.extend(
                [
                    "--std=c++20",
                    "--expt-relaxed-constexpr",
                    "--expt-extended-lambda",
                    "--diag-suppress=39,68,161,174,177,186,940,3012",
                    "-Xptxas",
                    "--register-usage-level=10",
                    "-DEP_NUM_TOPK_IDX_BITS=32",
                ]
                .map(str::to_string),
            );
            nvcc_args.extend([
                "-I".to_string(),
                root.join("third_party/DeepEP/deep_ep/include")
                    .to_string_lossy()
                    .to_string(),
                "-I".to_string(),
                nccl_root.join("include").to_string_lossy().to_string(),
            ]);
        }

        if stem.starts_with("kimi_") || stem.starts_with("marlin_nvfp4") {
            for dir in &flashinfer.cccl {
                nvcc_args.extend(["-I".to_string(), dir.to_string_lossy().to_string()]);
            }
            nvcc_args.extend([
                "--std=c++17".to_string(),
                "--expt-relaxed-constexpr".to_string(),
                "-I".to_string(),
                flashinfer.include.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.csrc.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.cutlass.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.cutlass_util.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.spdlog.to_string_lossy().to_string(),
                "-I".to_string(),
                csrc_dir.join("marlin").to_string_lossy().to_string(),
                "-I".to_string(),
                csrc_dir
                    .join("marlin/vllm_marlin")
                    .to_string_lossy()
                    .to_string(),
            ]);
        }

        if stem == "glm52_flashmla_sparse" {
            let flashmla = root.join("third_party/FlashMLA/csrc");
            nvcc_args.extend([
                "--std=c++20".to_string(),
                "--expt-relaxed-constexpr".to_string(),
                "--expt-extended-lambda".to_string(),
                "-I".to_string(),
                flashmla.to_string_lossy().to_string(),
                "-I".to_string(),
                flashmla
                    .join("cutlass/include")
                    .to_string_lossy()
                    .to_string(),
                "-I".to_string(),
                flashmla
                    .join("cutlass/tools/util/include")
                    .to_string_lossy()
                    .to_string(),
                "-I".to_string(),
                flashmla
                    .join("kerutils/include")
                    .to_string_lossy()
                    .to_string(),
                "-I".to_string(),
                flashinfer.cutlass.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.cutlass_util.to_string_lossy().to_string(),
            ]);
        } else if stem == "glm52_fp8_gemm" {
            for dir in &flashinfer.cccl {
                nvcc_args.extend(["-I".to_string(), dir.to_string_lossy().to_string()]);
            }
            nvcc_args.extend([
                "--std=c++17".to_string(),
                "--expt-relaxed-constexpr".to_string(),
                "--expt-extended-lambda".to_string(),
                "-I".to_string(),
                flashinfer.include.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.cutlass.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.cutlass_util.to_string_lossy().to_string(),
            ]);
        } else if stem == "glm52_flashinfer_sparse" {
            for dir in &flashinfer.cccl {
                nvcc_args.extend(["-I".to_string(), dir.to_string_lossy().to_string()]);
            }
            nvcc_args.extend([
                "--std=c++17".to_string(),
                "--expt-relaxed-constexpr".to_string(),
                "--expt-extended-lambda".to_string(),
                "-DTLLM_GEN_FMHA_CUBIN_PATH=\"embedded\"".to_string(),
                "-DTLLM_GEN_FMHA_METAINFO_HASH=\"pegainfer-glm52-sm100f\"".to_string(),
                "-I".to_string(),
                out_dir.to_string_lossy().to_string(),
                "-I".to_string(),
                csrc_dir
                    .join("glm52/trtllm_gen")
                    .to_string_lossy()
                    .to_string(),
                "-I".to_string(),
                flashinfer.include.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.csrc.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.cutlass.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.cutlass_util.to_string_lossy().to_string(),
                "-I".to_string(),
                flashinfer.spdlog.to_string_lossy().to_string(),
            ]);
        } else if stem == "glm52_deepgemm_mqa" || stem == "glm52_deepgemm_grouped_sm100" {
            // DeepGEMM MQA + masked grouped GEMM kernels,
            // AOT-instantiated from the vendored device headers (torch-free
            // via DG_NO_TORCH, no runtime JIT). Needs DeepGEMM csrc headers +
            // CUTLASS + fmt, C++20.
            let deepgemm_root = root.join("third_party/DeepGEMM");
            let deepgemm_csrc = deepgemm_root.join("csrc");
            let deepgemm_include = deepgemm_root.join("deep_gemm/include");
            let cutlass_include = deepgemm_root.join("third-party/cutlass/include");
            let cutlass_util = deepgemm_root.join("third-party/cutlass/tools/util/include");
            let fmt_include = deepgemm_root.join("third-party/fmt/include");
            nvcc_args.extend([
                "--std=c++20".to_string(),
                "--expt-relaxed-constexpr".to_string(),
                "--expt-extended-lambda".to_string(),
                "-DDG_NO_TORCH".to_string(),
                "-I".to_string(),
                deepgemm_csrc.to_string_lossy().to_string(),
                "-I".to_string(),
                deepgemm_include.to_string_lossy().to_string(),
                "-I".to_string(),
                cutlass_include.to_string_lossy().to_string(),
                "-I".to_string(),
                cutlass_util.to_string_lossy().to_string(),
                "-I".to_string(),
                fmt_include.to_string_lossy().to_string(),
            ]);
        } else if stem.starts_with("glm52_") {
            nvcc_args.extend(["--std=c++17".to_string()]);
        // --- k3 ---
        } else if is_k3_source(&csrc_dir, cu_file) {
            // K3 FP8xFP4 masked grouped GEMM, AOT-instantiated from the
            // vendored DeepGEMM device headers (torch-free via DG_NO_TORCH, no
            // runtime JIT). Same flags/includes as the GLM5.2 DeepGEMM stems.
            let deepgemm_root = root.join("third_party/DeepGEMM");
            let deepgemm_csrc = deepgemm_root.join("csrc");
            let deepgemm_include = deepgemm_root.join("deep_gemm/include");
            let cutlass_include = deepgemm_root.join("third-party/cutlass/include");
            let cutlass_util = deepgemm_root.join("third-party/cutlass/tools/util/include");
            let fmt_include = deepgemm_root.join("third-party/fmt/include");
            nvcc_args.extend([
                "--std=c++20".to_string(),
                "--expt-relaxed-constexpr".to_string(),
                "--expt-extended-lambda".to_string(),
                "-DDG_NO_TORCH".to_string(),
                "-I".to_string(),
                deepgemm_csrc.to_string_lossy().to_string(),
                "-I".to_string(),
                deepgemm_include.to_string_lossy().to_string(),
                "-I".to_string(),
                cutlass_include.to_string_lossy().to_string(),
                "-I".to_string(),
                cutlass_util.to_string_lossy().to_string(),
                "-I".to_string(),
                fmt_include.to_string_lossy().to_string(),
            ]);
            // --- end k3 ---
        }

        nvcc_tasks.push(NvccTask {
            cu_file: cu_file.clone(),
            obj_file,
            args: nvcc_args,
        });
    }

    if !moe_enabled {
        println!(
            "cargo:warning=MoE third-party substrate disabled; enable the pegainfer-kernels `moe` feature to build DeepEP-backed kernels"
        );
    }
    if !glm52_enabled {
        println!(
            "cargo:warning=GLM5.2 DeepGEMM/FlashMLA interfaces disabled; enable the pegainfer-kernels `glm52` feature to build them"
        );
    }
    if !kimi_k2_enabled {
        println!(
            "cargo:warning=Kimi-K2 CUDA kernels disabled; enable the pegainfer-kernels `kimi-k2` feature to build them"
        );
    }

    // tilelang: BEGIN
    if cfg!(feature = "gemma4") {
        nvcc_tasks.extend(tilelang_nvcc_tasks(
            &GEMMA4_TILELANG,
            &out_dir,
            &cuda_include,
            &arch_args,
            &sm_targets,
            &nvcc,
        ));
    } else {
        println!(
            "cargo:warning=Gemma 4 TileLang kernels disabled; enable the pegainfer-kernels `gemma4` feature to build them"
        );
    }
    if cfg!(feature = "k3") {
        nvcc_tasks.extend(tilelang_nvcc_tasks(
            &K3_TILELANG,
            &out_dir,
            &cuda_include,
            &arch_args,
            &sm_targets,
            &nvcc,
        ));
        // The vendored FlashKDA sources ride into csrc/k3/k3_flash_kda.cu by
        // include; csrc rerun tracking does not see them.
        for vendored in [
            "third_party/flash-kda/csrc/fwd.h",
            "third_party/flash-kda/csrc/smxx/utils.cuh",
            "third_party/flash-kda/csrc/smxx/fwd_kernel1.cuh",
            "third_party/flash-kda/csrc/smxx/fwd_kernel2.cuh",
            "third_party/flash-kda/csrc/smxx/fwd_launch.cu",
        ] {
            println!("cargo:rerun-if-changed={}", root.join(vendored).display());
        }
    } else {
        println!(
            "cargo:warning=K3 TileLang kernels disabled; enable the pegainfer-kernels `k3` feature to build them"
        );
    }
    // tilelang: END

    nvcc_tasks.sort_by_key(|task| nvcc_task_priority(&task.cu_file));

    let task_queue = Mutex::new(VecDeque::from(nvcc_tasks));
    let nvcc_workers = nvcc_jobs.min(task_queue.lock().expect("task queue poisoned").len());
    let mut obj_files = Vec::new();
    thread::scope(|scope| {
        let handles: Vec<_> = (0..nvcc_workers)
            .map(|_| {
                let task_queue = &task_queue;
                let nvcc = nvcc.clone();
                scope.spawn(move || {
                    let mut completed = Vec::new();
                    loop {
                        let task = task_queue.lock().expect("task queue poisoned").pop_front();
                        let Some(task) = task else {
                            break;
                        };

                        let status = time_phase(format!("nvcc {}", task.cu_file.display()), || {
                            Command::new(&nvcc)
                                .args(&task.args)
                                .status()
                                .unwrap_or_else(|_| {
                                    panic!("Failed to run nvcc for {}", task.cu_file.display())
                                })
                        });
                        completed.push((task.cu_file, task.obj_file, status));
                    }
                    completed
                })
            })
            .collect();

        for handle in handles {
            for (cu_file, obj_file, status) in handle.join().expect("nvcc worker panicked") {
                assert!(
                    status.success(),
                    "nvcc compilation failed for {}",
                    cu_file.display()
                );
                obj_files.push(obj_file);
            }
        }
    });
    obj_files.sort();

    // The optional kernel-lab .so (linked below) uses the same objects; the
    // ar invocation consumes the vector.
    let kernel_lab_objs = obj_files.clone();

    let cuda_lib = out_dir.join("libkernels_cuda.a");
    let _ = fs::remove_file(&cuda_lib);
    let mut ar_args = vec!["rcs".to_string(), cuda_lib.to_string_lossy().to_string()];
    ar_args.extend(
        obj_files
            .into_iter()
            .map(|path| path.to_string_lossy().to_string()),
    );

    let status = time_phase("ar libkernels_cuda.a", || {
        Command::new("ar")
            .args(&ar_args)
            .status()
            .expect("Failed to run ar")
    });

    assert!(status.success(), "ar failed");

    // Optional kernel-lab shared object for the Python bench harness
    // (pegainfer-glm52/benches/kernel_lab): the exact production objects —
    // same sources, same nvcc flags — linked as a dlopen-able .so. Skipped
    // entirely unless PEGAINFER_KERNEL_LAB is set, so default builds run zero
    // extra commands and zero extra link lines.
    if std::env::var_os("PEGAINFER_KERNEL_LAB").is_some() {
        link_kernel_lab_shared(&nvcc, &toolkit, &out_dir, &kernel_lab_objs);
    }

    if qwen35_enabled {
        compile_triton_aot_kernels(&cuda_include, &out_dir, &sm_targets);
    } else {
        println!(
            "cargo:warning=Qwen3.5 Triton AOT kernels disabled; enable the pegainfer-kernels `qwen35` feature to build them (needs Python + Triton at build time)"
        );
    }

    println!("cargo:rustc-link-search=native={}", out_dir.display());
    if cfg!(target_os = "windows") {
        println!(
            "cargo:rustc-link-search=native={}/lib/x64",
            toolkit.root.display()
        );
    } else {
        toolkit.link_search();
    }
    println!("cargo:rustc-link-lib=static=kernels_cuda");
    println!("cargo:rustc-link-lib=cudart");
    println!("cargo:rustc-link-lib=cublas");
    println!("cargo:rustc-link-lib=cublasLt");
    // DeepGEMM JIT runtime calls cuLibraryLoadData etc. (CUDA 12.6+ driver API);
    // libcuda.so lives in the system lib dir, not the toolkit dir.
    println!("cargo:rustc-link-lib=cuda");
    // DeepGEMM compiler.hpp references nvrtc symbols (NVRTCCompiler class).
    println!("cargo:rustc-link-lib=nvrtc");
    if let Some(nccl_root) = &deepep_nccl {
        link_deepep_nccl(nccl_root, &out_dir);
    }
    if !cfg!(target_os = "windows") {
        println!("cargo:rustc-link-lib=stdc++");
    }

    println!("cargo:rerun-if-changed={}", root.join("csrc").display());
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=PEGAINFER_CUDA_SM");
    println!("cargo:rerun-if-env-changed=CUDA_SM");
    println!("cargo:rerun-if-env-changed=PEGAINFER_FLASHINFER_INCLUDE");
    println!("cargo:rerun-if-env-changed=PEGAINFER_BUILD_TIMING");
    println!("cargo:rerun-if-env-changed=PEGAINFER_NVCC_JOBS");
    println!("cargo:rerun-if-env-changed=PEGAINFER_NCCL_ROOT");
    let mut tracked_dirs = vec![
        flashinfer.include.clone(),
        flashinfer.csrc.clone(),
        flashinfer.cutlass.clone(),
        flashinfer.cutlass_util.clone(),
        flashinfer.spdlog.clone(),
    ];
    tracked_dirs.extend(flashinfer.cccl.iter().cloned());
    tracked_dirs.push(root.join("third_party/DeepEP/deep_ep/include"));
    tracked_dirs.push(root.join("third_party/DeepGEMM"));
    tracked_dirs.push(root.join("third_party/FlashMLA"));
    for dir in tracked_dirs {
        if dir.exists() {
            println!("cargo:rerun-if-changed={}", dir.display());
        }
    }
}
