fn generate_glm52_trtllm_fmha_cubins(root: &Path, out_dir: &Path) {
    let cubin_dir = root.join("cubin/glm52");
    let mut generated = String::from(
        "// Generated by pegainfer-kernels/build.rs from the checked-in FlashInfer cubins.\n\
         #pragma once\n\n",
    );
    for &(symbol, file_name) in GLM52_TRTLLM_FMHA_CUBINS {
        let path = cubin_dir.join(file_name);
        println!("cargo:rerun-if-changed={}", path.display());
        let bytes = fs::read(&path).unwrap_or_else(|err| {
            panic!(
                "failed to read GLM5.2 TRTLLM FMHA cubin {}: {err}",
                path.display()
            )
        });
        writeln!(&mut generated, "static const unsigned char {symbol}[] = {{")
            .expect("write cubin array declaration");
        for chunk in bytes.chunks(16) {
            generated.push_str("  ");
            for byte in chunk {
                write!(&mut generated, "0x{byte:02x}, ").expect("write cubin byte");
            }
            generated.push('\n');
        }
        generated.push_str("};\n");
        writeln!(
            &mut generated,
            "static constexpr unsigned int {symbol}Size = sizeof({symbol});\n"
        )
        .expect("write cubin array size");
    }
    let output = out_dir.join("glm52_trtllm_fmha_cubins.inc");
    fs::write(&output, generated).unwrap_or_else(|err| {
        panic!(
            "failed to write generated GLM5.2 TRTLLM FMHA cubin header {}: {err}",
            output.display()
        )
    });
}

